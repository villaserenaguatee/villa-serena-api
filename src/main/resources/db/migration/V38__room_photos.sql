-- V38: Photographs belong to the physical room, independently of its category.
CREATE TABLE room_photos (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 room_id bigint NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
 object_key text NOT NULL,
 is_primary boolean NOT NULL DEFAULT false,
 sort_order integer NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
 UNIQUE(room_id, object_key),
 UNIQUE(room_id, sort_order)
);
CREATE UNIQUE INDEX ux_room_photos_primary ON room_photos(room_id) WHERE is_primary;
